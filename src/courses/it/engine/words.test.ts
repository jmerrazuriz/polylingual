import { describe, expect, it } from 'vitest'
import { articleReason, articulated, bello, definiteArticle, type Noun, quello, withArticulated, withDefinite, withIndefinite, withPartitive, withPossessive } from './articles'
import { numberReason, numberToWords, ordinal } from './numbers'
import { startOf } from './phonetics'
import { pluralOf, pluralReason } from './plurals'
import { combined, enclitic } from './pronouns'

const n = (word: string, gender: 'm' | 'f', extra: Partial<Noun> = {}): Noun => ({ word, gender, ...extra })

describe('artículos', () => {
  it('el definido según el sonido inicial', () => {
    expect(withDefinite(n('libro', 'm'))).toBe('il libro')
    expect(withDefinite(n('studente', 'm'))).toBe('lo studente')
    expect(withDefinite(n('zaino', 'm'))).toBe('lo zaino')
    expect(withDefinite(n('gnomo', 'm'))).toBe('lo gnomo')
    expect(withDefinite(n('psicologo', 'm'))).toBe('lo psicologo')
    expect(withDefinite(n('yogurt', 'm'))).toBe('lo yogurt')
    expect(withDefinite(n('amico', 'm'))).toBe("l'amico")
    expect(withDefinite(n('hotel', 'm'))).toBe("l'hotel")
    expect(withDefinite(n('casa', 'f'))).toBe('la casa')
    expect(withDefinite(n('amica', 'f'))).toBe("l'amica")
    expect(withDefinite(n('libro', 'm'), true)).toBe('i libri')
    expect(withDefinite(n('studente', 'm'), true)).toBe('gli studenti')
    expect(withDefinite(n('amico', 'm'), true)).toBe('gli amici')
    expect(withDefinite(n('amica', 'f'), true)).toBe('le amiche')
    expect(withDefinite(n('uomo', 'm', { plural: 'uomini' }), true)).toBe('gli uomini')
    expect(withDefinite(n('uovo', 'm', { plural: 'uova', pluralGender: 'f' }), true)).toBe('le uova')
    expect(startOf('idea')).toBe('vowel')
    expect(startOf('iogurt')).toBe('special')
  })

  it('el indefinido y el partitivo', () => {
    expect(withIndefinite(n('libro', 'm'))).toBe('un libro')
    expect(withIndefinite(n('amico', 'm'))).toBe('un amico')
    expect(withIndefinite(n('zio', 'm'))).toBe('uno zio')
    expect(withIndefinite(n('casa', 'f'))).toBe('una casa')
    expect(withIndefinite(n('amica', 'f'))).toBe("un'amica")
    expect(withIndefinite(n('studentessa', 'f'))).toBe('una studentessa')
    expect(withPartitive(n('pane', 'm'))).toBe('del pane')
    expect(withPartitive(n('zucchero', 'm'))).toBe('dello zucchero')
    expect(withPartitive(n('acqua', 'f'))).toBe("dell'acqua")
    expect(withPartitive(n('amico', 'm'), true)).toBe('degli amici')
    expect(withPartitive(n('mela', 'f'), true)).toBe('delle mele')
  })

  it('las preposiciones articuladas', () => {
    expect(articulated('di', 'il')).toBe('del')
    expect(articulated('a', 'lo')).toBe('allo')
    expect(articulated('da', "l'")).toBe("dall'")
    expect(articulated('in', 'la')).toBe('nella')
    expect(articulated('su', 'i')).toBe('sui')
    expect(articulated('in', 'gli')).toBe('negli')
    expect(articulated('su', 'le')).toBe('sulle')
    expect(articulated('in', 'il')).toBe('nel')
    expect(withArticulated('a', n('stazione', 'f'))).toBe('alla stazione')
    expect(withArticulated('in', n('ufficio', 'm'))).toBe("nell'ufficio")
    expect(withArticulated('su', n('tavolo', 'm'))).toBe('sul tavolo')
    expect(withArticulated('da', n('amico', 'm'), true)).toBe('dagli amici')
  })

  it('quello, bello y los posesivos', () => {
    expect(quello(n('libro', 'm'))).toBe('quel')
    expect(quello(n('studente', 'm'))).toBe('quello')
    expect(quello(n('amico', 'm'))).toBe("quell'")
    expect(quello(n('amico', 'm'), true)).toBe('quegli')
    expect(quello(n('libro', 'm'), true)).toBe('quei')
    expect(bello(n('ragazzo', 'm'), true)).toBe('bei')
    expect(bello(n('albero', 'm'), true)).toBe('begli')
    expect(withPossessive(0, n('casa', 'f'))).toBe('la mia casa')
    expect(withPossessive(0, n('amico', 'm'), true)).toBe('i miei amici')
    expect(withPossessive(0, n('madre', 'f', { family: true }))).toBe('mia madre')
    expect(withPossessive(1, n('fratello', 'm', { family: true }), true)).toBe('i tuoi fratelli')
    expect(withPossessive(5, n('padre', 'm', { family: true }))).toBe('il loro padre')
    expect(withPossessive(2, n('zio', 'm', { family: true, plural: 'zii' }), true)).toBe('i suoi zii')
  })

  it('explica por qué se usa cada artículo', () => {
    expect(articleReason(n('studente', 'm'), 'lo')).toMatch(/s \+ consonante/)
    expect(articleReason(n('zaino', 'm'), 'lo')).toMatch(/z/)
    expect(articleReason(n('amico', 'm'), "l'")).toMatch(/vocal/)
    expect(articleReason(n('amica', 'f'), "un'")).toMatch(/un’/)
    expect(articleReason(n('amico', 'm'), 'un')).toMatch(/sin apóstrofo/)
    expect(definiteArticle(n('dio', 'm', { plural: 'dei' }), true)).toBe('gli')
  })
})

describe('plurales', () => {
  it('reglas generales e invariables', () => {
    expect(pluralOf(n('libro', 'm'))).toBe('libri')
    expect(pluralOf(n('casa', 'f'))).toBe('case')
    expect(pluralOf(n('fiore', 'm'))).toBe('fiori')
    expect(pluralOf(n('chiave', 'f'))).toBe('chiavi')
    expect(pluralOf(n('problema', 'm'))).toBe('problemi')
    expect(pluralOf(n('città', 'f'))).toBe('città')
    expect(pluralOf(n('caffè', 'm'))).toBe('caffè')
    expect(pluralOf(n('film', 'm'))).toBe('film')
    expect(pluralOf(n('re', 'm'))).toBe('re')
    expect(pluralOf(n('crisi', 'f'))).toBe('crisi')
    expect(pluralOf(n('serie', 'f'))).toBe('serie')
    expect(pluralOf(n('foto', 'f', { invariable: true }))).toBe('foto')
    expect(pluralOf(n('via', 'f'))).toBe('vie')
    expect(pluralOf(n('zia', 'f'))).toBe('zie')
  })

  it('-co, -go, -ca, -cia, -gia e -io', () => {
    expect(pluralOf(n('parco', 'm'))).toBe('parchi')
    expect(pluralOf(n('tedesco', 'm'))).toBe('tedeschi')
    expect(pluralOf(n('amico', 'm'))).toBe('amici')
    expect(pluralOf(n('medico', 'm'))).toBe('medici')
    expect(pluralOf(n('antico', 'm'))).toBe('antichi')
    expect(pluralOf(n('fico', 'm'))).toBe('fichi')
    expect(pluralOf(n('greco', 'm'))).toBe('greci')
    expect(pluralOf(n('lago', 'm'))).toBe('laghi')
    expect(pluralOf(n('dialogo', 'm'))).toBe('dialoghi')
    expect(pluralOf(n('psicologo', 'm'))).toBe('psicologi')
    expect(pluralOf(n('amica', 'f'))).toBe('amiche')
    expect(pluralOf(n('collega', 'm'))).toBe('colleghi')
    expect(pluralOf(n('camicia', 'f'))).toBe('camicie')
    expect(pluralOf(n('valigia', 'f'))).toBe('valigie')
    expect(pluralOf(n('arancia', 'f'))).toBe('arance')
    expect(pluralOf(n('spiaggia', 'f'))).toBe('spiagge')
    expect(pluralOf(n('farmacia', 'f'))).toBe('farmacie')
    expect(pluralOf(n('allergia', 'f'))).toBe('allergie')
    expect(pluralOf(n('figlio', 'm'))).toBe('figli')
    expect(pluralOf(n('negozio', 'm'))).toBe('negozi')
    expect(pluralOf(n('zio', 'm', { plural: 'zii' }))).toBe('zii')
  })

  it('explica la regla', () => {
    expect(pluralReason(n('parco', 'm'))).toMatch(/-chi/)
    expect(pluralReason(n('città', 'f'))).toMatch(/acentuada/)
    expect(pluralReason(n('uovo', 'm', { plural: 'uova' }))).toMatch(/irregular/)
    expect(pluralReason(n('arancia', 'f'))).toMatch(/consonante/)
  })
})

describe('pronombres', () => {
  it('combinados y pegados', () => {
    expect(combined('mi', 'lo')).toBe('me lo')
    expect(combined('ti', 'ne')).toBe('te ne')
    expect(combined('gli', 'lo')).toBe('glielo')
    expect(combined('le', 'la')).toBe('gliela')
    expect(combined('gli', 'ne')).toBe('gliene')
    expect(combined('ci', 'li')).toBe('ce li')
    expect(combined('si', 'ne')).toBe('se ne')
    expect(enclitic("di'", 'mi')).toBe('dimmi')
    expect(enclitic("fa'", 'lo')).toBe('fallo')
    expect(enclitic("da'", 'gli')).toBe('dagli')
    expect(enclitic("da'", 'me lo')).toBe('dammelo')
    expect(enclitic("va'", 'te ne')).toBe('vattene')
    expect(enclitic('parla', 'gli')).toBe('parlagli')
    expect(enclitic('vedere', 'lo')).toBe('vederlo')
    expect(enclitic('dare', 'glielo')).toBe('darglielo')
  })
})

describe('números', () => {
  it('escribe los números en una palabra, con elisión y tilde', () => {
    expect(numberToWords(0)).toBe('zero')
    expect(numberToWords(3)).toBe('tre')
    expect(numberToWords(17)).toBe('diciassette')
    expect(numberToWords(21)).toBe('ventuno')
    expect(numberToWords(23)).toBe('ventitré')
    expect(numberToWords(28)).toBe('ventotto')
    expect(numberToWords(33)).toBe('trentatré')
    expect(numberToWords(48)).toBe('quarantotto')
    expect(numberToWords(100)).toBe('cento')
    expect(numberToWords(101)).toBe('centouno')
    expect(numberToWords(103)).toBe('centotré')
    expect(numberToWords(108)).toBe('centotto')
    expect(numberToWords(180)).toBe('centottanta')
    expect(numberToWords(1000)).toBe('mille')
    expect(numberToWords(1984)).toBe('millenovecentottantaquattro')
    expect(numberToWords(2000)).toBe('duemila')
    expect(numberToWords(2026)).toBe('duemilaventisei')
    expect(numberToWords(21000)).toBe('ventunmila')
    expect(numberToWords(1000000)).toBe('un milione')
    expect(numberToWords(2500000)).toBe('due milioni cinquecentomila')
  })

  it('ordinales y explicación', () => {
    expect(ordinal(1)).toBe('primo')
    expect(ordinal(3, true)).toBe('terza')
    expect(ordinal(11)).toBe('undicesimo')
    expect(ordinal(20)).toBe('ventesimo')
    expect(ordinal(21)).toBe('ventunesimo')
    expect(ordinal(23)).toBe('ventitreesimo')
    expect(ordinal(26)).toBe('ventiseiesimo')
    expect(ordinal(100)).toBe('centesimo')
    expect(ordinal(1000)).toBe('millesimo')
    expect(numberReason(28)).toMatch(/otto/)
    expect(numberReason(23)).toMatch(/tilde/)
  })
})
