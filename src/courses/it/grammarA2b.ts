const c = (prompt: string, answer: string, whyWrong: Record<string, string>, explanation: string, hint?: string): GrammarExercise => ({
  type: 'choice',
  prompt,
  ...(hint ? { hint } : {}),
  options: [answer, ...Object.keys(whyWrong)],
  answer,
  explanation,
  whyWrong,
})
const m = (text: string, answer: string, whyWrong: Record<string, string>, explanation: string): GrammarExercise => ({
  type: 'meaning',
  text,
  options: [answer, ...Object.keys(whyWrong)],
  answer,
  explanation,
  whyWrong,
})
