/** Opción: la respuesta y, por cada opción incorrecta, por qué no sirve. */
const c = (prompt: string, answer: string, whyWrong: Record<string, string>, explanation: string, hint?: string): GrammarExercise => ({
  type: 'choice',
  prompt,
  ...(hint ? { hint } : {}),
  options: [answer, ...Object.keys(whyWrong)],
  answer,
  explanation,
  whyWrong,
})
/** Qué significa la frase. */
const m = (text: string, answer: string, whyWrong: Record<string, string>, explanation: string): GrammarExercise => ({
  type: 'meaning',
  text,
  options: [answer, ...Object.keys(whyWrong)],
  answer,
  explanation,
  whyWrong,
})
/** Escribir en italiano. */
const t = (prompt: string, answers: string[], explanation: string): GrammarExercise => ({ type: 'type', prompt, answers, italian: true, explanation })
/** Ordenar las palabras (sin puntuación suelta). */
const o = (meaning: string, sentence: string, explanation: string): GrammarExercise => ({ type: 'order', meaning, answer: sentence.split(' '), explanation })
const ex = (text: string, meaning: string) => ({ text, meaning })

